/*
 * Модуль системного таймера
 * 
 * Реализует таймер на базе встроенной функции millis().
 * Предоставляет функциональность для отсчета времени и определения
 * истечения заданного периода без использования блокирующих задержек.
 * 
 * Примечание: При переопределении прерываний таймеров может работать некорректно.
 */

#pragma once
#include <Arduino.h>

class Timer {
public:
    /**
     * Конструктор таймера
     * 
     * @param period Период срабатывания таймера в миллисекундах.
     *               Через этот период isReady() вернет true и сбросит таймер.
     *               Таймер автоматически сбрасывается при создании.
     */
    Timer(unsigned long period = 0);
    
    /**
     * Возвращает количество миллисекунд, прошедших с момента
     * последнего сброса таймера (через drop() или при создании).
     * 
     * @return Время в миллисекундах
     * 
     * Примечание: Корректно обрабатывает переполнение millis() благодаря
     * модульной арифметике для unsigned long.
     */
    inline unsigned long getTime() {
        // Используем модульную арифметику для корректной обработки переполнения millis().
        // Для unsigned long вычитание автоматически обрабатывает переполнение: если millis()
        // переполнился и стал меньше _initTime, результат всё равно равен количеству
        // миллисекунд, прошедших с момента сброса.
        return millis() - _initTime;
    }
    
    /**
     * Проверяет, истек ли заданный период.
     * Если период истек, автоматически сбрасывает таймер.
     * 
     * @return true если период истек, false в противном случае
     */
    bool isReady();
    
    /**
     * Устанавливает новый период срабатывания таймера.
     * 
     * @param period Новый период в миллисекундах
     * @param dropTimer Если true, таймер сбрасывается после установки периода.
     *                  Это предотвращает немедленное срабатывание isReady(),
     *                  если с момента последнего сброса уже прошел период.
     */
    void setPeriod(unsigned long period, bool dropTimer = true);
    
    /**
     * Возвращает текущий установленный период таймера.
     * 
     * @return Период в миллисекундах
     */
    inline unsigned long getPeriod() const {
        // Позволяет проверять текущий установленный период (например, при диагностике).
        return _period;
    }
    
    /**
     * Сбрасывает таймер (осуществляет его перезапуск).
     * Время отсчета начинается заново с текущего момента.
     */
    inline void drop() {
        // Сохраняем текущее значение millis() как начало отсчёта.
        _initTime = millis();
    }

private:
    unsigned long _initTime;  // Время последнего сброса таймера (millis())
    unsigned long _period;    // Период срабатывания таймера в миллисекундах
};

