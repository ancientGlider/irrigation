#include "timer.h"

Timer::Timer(unsigned long period) {
    // Сбрасываем таймер и устанавливаем период через единый метод,
    // чтобы не дублировать логику и гарантировать корректную инициализацию.
    setPeriod(period);
}

bool Timer::isReady() {
    // Фиксируем прошедшее время. Для unsigned long вычитание корректно обрабатывает
    // переполнение, поэтому дополнительной логики для roll-over не требуется.
    if (getTime() >= _period) {
        // Сбрасываем таймер сразу после срабатывания — вызывающему коду не нужно
        // заботиться о повторном запуске.
        drop();
        return true;
    }
    
    return false;
}

void Timer::setPeriod(unsigned long period, bool dropTimer) {
    // Период «0» означает, что таймер всегда готов (используется для мгновенных проверок).
    _period = period;
    if (dropTimer) {
        // При изменении периода по умолчанию начинаем отсчёт заново.
        drop();
    }
}

