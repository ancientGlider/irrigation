/*
 * Модуль датчика влажности почвы
 * 
 * Реализует работу с аналоговым датчиком влажности почвы (емкостным или резистивным)
 * с использованием конечного автомата (FSM) для асинхронной работы без блокирующих задержек.
 * 
 * Особенности:
 * - Управление питанием датчика для защиты от коррозии
 * - Калибровка с поддержкой прямой и обратной зависимости показаний
 * - Периодический опрос датчика (по умолчанию каждые 10 минут)
 * - Поддержка принудительной проверки
 * 
 * Требуется модуль: timer
 */

#pragma once
#include <Arduino.h>
#include "../timer/timer.h"

// Константы для работы датчика
#define SOIL_SENSOR_DEFAULT_CHECK_PERIOD    600000UL  // Периодичность опроса по умолчанию (10 минут в миллисекундах)
#define SOIL_SENSOR_STAB_PAUSE              60UL      // Время стабилизации показаний датчика (миллисекунды)

// Состояния конечного автомата
#define SOIL_SENSOR_UNINITIALIZED       0
#define SOIL_SENSOR_BEGIN_READING       1
#define SOIL_SENSOR_READ_DATA           2
#define SOIL_SENSOR_IDLE                3

class SoilSensor {
public:
    /**
     * Конструктор датчика влажности почвы
     * 
     * @param pinInput Аналоговый пин Arduino, к которому подключен датчик
     * @param pinVCC Цифровой пин Arduino, управляющий питанием датчика
     * @param checkPeriod Периодичность опроса датчика в миллисекундах (по умолчанию 10 минут)
     */
    SoilSensor(uint8_t pinInput, uint8_t pinVCC, unsigned long checkPeriod = SOIL_SENSOR_DEFAULT_CHECK_PERIOD);
    
    /**
     * Инициализация датчика
     * Настраивает пины и запускает первый цикл чтения
     */
    void begin();
    
    /**
     * Возвращает относительную влажность почвы в процентах (0-100%)
     * 
     * @param forceCheck Если true, принудительно запускает проверку датчика
     * @return Влажность в процентах (0-100)
     * 
     * Примечание: Значение рассчитывается на основе калибровочных значений min/max.
     * Поддерживает как прямую (резистивные датчики), так и обратную (емкостные датчики) зависимость.
     */
    uint8_t getSensorData(bool forceCheck = false);
    
    /**
     * Возвращает сырые показания датчика (0-1023)
     * 
     * @param forceCheck Если true, принудительно запускает проверку датчика
     * @return Сырое значение аналогового входа (0-1023)
     */
    inline int getRawSensorData(bool forceCheck = false) {
        // Возвращаем необработанное значение АЦП. При необходимости запускаем
        // новый цикл чтения (forceCheck) или используем автоматический опрос.
        _checkSensor(forceCheck || _timer.isReady());
        return _humidity;
    }
    
    /**
     * Устанавливает калибровочные значения для расчета относительной влажности
     * 
     * @param minHumidity Значение датчика, соответствующее 0% влажности (0-1023)
     * @param maxHumidity Значение датчика, соответствующее 100% влажности (0-1023)
     * 
     * Примечание: 
     * - Для резистивных датчиков: min < max (при повышении влажности показания растут)
     * - Для емкостных датчиков: min > max (при повышении влажности показания падают)
     * - Если min == max, калибровка не изменяется (предотвращение деления на ноль)
     */
    void calibrate(int minHumidity, int maxHumidity);

private:
    const uint8_t _pinInput;      // Аналоговый пин датчика
    const uint8_t _pinVCC;        // Пин управления питанием датчика
    unsigned long _checkPeriod;   // Периодичность опроса датчика (миллисекунды)
    uint8_t _state;               // Текущее состояние FSM
    Timer _timer;                 // Таймер для периодичности опроса и стабилизации
    int _humidity;                // Последнее прочитанное значение датчика (0-1023)
    int _minHumidity;             // Калибровочное значение для 0% влажности
    int _maxHumidity;             // Калибровочное значение для 100% влажности
    
    /**
     * Обрабатывает конечный автомат для чтения датчика
     * 
     * @param forceCheck Если true, принудительно запускает цикл чтения
     */
    void _checkSensor(bool forceCheck);
};

